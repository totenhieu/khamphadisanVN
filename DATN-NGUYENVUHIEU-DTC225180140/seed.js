async function insertData() {
  // Để vượt qua lỗi chứng chỉ https tạm thời
  process.env.NODE_TLS_REJECT_UNAUTHORIZED = '0';
  
  for (const item of heritages) {
    try {
      const res = await fetch("https://localhost:7216/api/heritage", {
        method: "POST",
        headers: {
          "Content-Type": "application/json"
        },
        body: JSON.stringify(item)
      });
      if (res.ok) {
        console.log("Thêm thành công: " + item.name);
      } else {
        const err = await res.text();
        console.log("Lỗi khi thêm " + item.name + ": " + err);
      }
    } catch (e) {
      console.log("Network error cho " + item.name, e.message);
    }
  }
}

